from typing import Protocol
from uuid import UUID

from .models import DatasetRecord, DatasetVersionRecord, ProcessingRunRecord


class Repository(Protocol):
    def create_dataset(self, dataset: DatasetRecord) -> DatasetRecord: ...
    def list_datasets(self) -> list[DatasetRecord]: ...
    def get_dataset(self, id: UUID) -> DatasetRecord | None: ...
    def create_version(self, v: DatasetVersionRecord) -> DatasetVersionRecord: ...
    def list_versions(self, id: UUID) -> list[DatasetVersionRecord]: ...
    def get_version(self, id: UUID) -> DatasetVersionRecord | None: ...
    def store_records(self, id: UUID, records: list[dict]): ...
    def get_records(self, id: UUID) -> list[dict]: ...
    def create_run(self, r: ProcessingRunRecord) -> ProcessingRunRecord: ...
    def list_runs(self, id: UUID | None = None) -> list[ProcessingRunRecord]: ...
    def get_run(self, id: UUID) -> ProcessingRunRecord | None: ...
